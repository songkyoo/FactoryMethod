using System.Text;

namespace Macaron.FactoryMethod;

internal static class SourceGenerationHelper
{
    public static GeneratedSource GenerateSource(SourceGenerationModel model)
    {
        var stringBuilder = new StringBuilder();

        stringBuilder.AppendLine("// <auto-generated />");
        stringBuilder.AppendLine("#nullable enable");
        stringBuilder.AppendLine();

        // namespace begin
        var hasNamespace = model.Namespace.Length > 0;
        if (hasNamespace)
        {
            stringBuilder.AppendLine($"namespace {model.Namespace}");
            stringBuilder.AppendLine("{");
        }

        var depthSpacerText = hasNamespace ? "    " : "";

        // nested type begin
        foreach (var typeDeclaration in model.TypeDeclarations)
        {
            stringBuilder.AppendLine($"{depthSpacerText}{typeDeclaration}");
            stringBuilder.AppendLine($"{depthSpacerText}{{");

            depthSpacerText += "    ";
        }

        // generate factory methods
        for (var i = 0; i < model.Methods.Length; i++)
        {
            var method = model.Methods[i];
            var paramList = string.Join(", ", method.Parameters.Select(x =>
            {
                return $"{x.Attribute}{x.Modifier}{x.Type} {x.Name}{x.DefaultValue}";
            }));
            var argList = string.Join(", ", method.Parameters.Select(x =>
            {
                return $"{(x.Modifier != "params " ? x.Modifier : "")}{x.Name}";
            }));

            if (i > 0)
            {
                stringBuilder.AppendLine();
            }

            stringBuilder.AppendLine($"{depthSpacerText}{method.AccessModifier} static {method.Type} {method.Name}({paramList}) => new({argList});");
        }

        // nested type end
        for (var i = 0; i < model.TypeDeclarations.Length; ++i)
        {
            depthSpacerText = depthSpacerText[..^4];

            stringBuilder.AppendLine($"{depthSpacerText}}}");
        }

        // namespace end
        if (hasNamespace)
        {
            stringBuilder.AppendLine("}");
        }

        return new GeneratedSource(model.HintName, stringBuilder.ToString());
    }
}
